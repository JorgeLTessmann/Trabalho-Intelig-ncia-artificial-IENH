# Normalização das pontuações

dataset_ia["Total_Normalizado"] = (
    (dataset_ia["Total"] - dataset_ia["Total"].min()) /
    (dataset_ia["Total"].max() - dataset_ia["Total"].min())
)

dataset_ia["Defesa_Normalizada"] = (
    (dataset_ia["Pontuacao_Defensiva"] - dataset_ia["Pontuacao_Defensiva"].min()) /
    (dataset_ia["Pontuacao_Defensiva"].max() - dataset_ia["Pontuacao_Defensiva"].min())
)

# Pontuação para seleção dos Pokémon

dataset_ia["Pontuacao_Final"] = (
    dataset_ia["Total_Normalizado"] * 0.6
    + dataset_ia["Defesa_Normalizada"] * 0.4
)


# 2. Montagem dos times

def montar_time(nome, quantidades):

    selecionados = []

    for perfil, quantidade in quantidades.items():

        candidatos = dataset_ia[
          dataset_ia["Perfil_Previsto"] == perfil
      ].sort_values("Pontuacao_Final", ascending=False)

        selecionados.append(candidatos.head(quantidade))

    time = pd.concat(selecionados).drop_duplicates("Nome")

    if len(time) < 6:
        restantes = dataset_ia[
            ~dataset_ia["Nome"].isin(time["Nome"])
        ].sort_values("Pontuacao_Final", ascending=False)

        time = pd.concat([
            time,
            restantes.head(6 - len(time))
        ])

    time = time.head(6).copy()
    time["Time"] = nome

    return time


